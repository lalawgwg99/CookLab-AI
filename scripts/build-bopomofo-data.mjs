// Build src/data/bopomofo.ts from Unihan_Readings.txt (kMandarin).
// Usage: node scripts/build-bopomofo-data.mjs /tmp/unihan/Unihan_Readings.txt
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const input = process.argv[2];
if (!input) { console.error("usage: build-bopomofo-data.mjs <Unihan_Readings.txt>"); process.exit(1); }

const INITIALS = { b: "ㄅ", p: "ㄆ", m: "ㄇ", f: "ㄈ", d: "ㄉ", t: "ㄊ", n: "ㄋ", l: "ㄌ", g: "ㄍ", k: "ㄎ", h: "ㄏ", j: "ㄐ", q: "ㄑ", x: "ㄒ", zh: "ㄓ", ch: "ㄔ", sh: "ㄕ", r: "ㄖ", z: "ㄗ", c: "ㄘ", s: "ㄙ" };
const FINALS = {
  a: "ㄚ", o: "ㄛ", e: "ㄜ", "ê": "ㄝ", ai: "ㄞ", ei: "ㄟ", ao: "ㄠ", ou: "ㄡ",
  an: "ㄢ", en: "ㄣ", ang: "ㄤ", eng: "ㄥ", er: "ㄦ",
  i: "ㄧ", ia: "ㄧㄚ", io: "ㄧㄛ", ie: "ㄧㄝ", iao: "ㄧㄠ", iu: "ㄧㄡ", iou: "ㄧㄡ", ian: "ㄧㄢ", in: "ㄧㄣ",
  iang: "ㄧㄤ", ing: "ㄧㄥ", iong: "ㄩㄥ",
  u: "ㄨ", ua: "ㄨㄚ", uo: "ㄨㄛ", uai: "ㄨㄞ", ui: "ㄨㄟ", uei: "ㄨㄟ", uan: "ㄨㄢ", un: "ㄨㄣ", uen: "ㄨㄣ",
  uang: "ㄨㄤ", ong: "ㄨㄥ",
  "ü": "ㄩ", "üe": "ㄩㄝ", "üan": "ㄩㄢ", "ün": "ㄩㄣ",
};
const TONE_MARK = { 1: "", 2: "ˊ", 3: "ˇ", 4: "ˋ", 5: "" };
const COMBINING_TONE = { "̄": 1, "́": 2, "̌": 3, "̀": 4 }; // U+0304/0301/030C/0300

function pinyinToBopomofo(raw) {
  const syl = raw.split(" ")[0];
  const nfd = syl.normalize("NFD").toLowerCase();
  let tone = 5, base = "";
  for (const ch of nfd) {
    if (COMBINING_TONE[ch]) { tone = COMBINING_TONE[ch]; continue; }
    if (ch === "̈") { base += "̈"; continue; } // combining diaeresis, resolved below
    if (/\p{M}/u.test(ch)) continue; // drop any other combining marks
    base += ch;
  }
  base = base.replaceAll("ü", "ü").replaceAll("u:", "ü").replaceAll("v", "ü");

  // Whole-syllable special cases: empty rhyme (zhi/chi/shi/ri/zi/ci/si), syllabic m/n/ng
  const EMPTY_RHYME = { zhi: "ㄓ", chi: "ㄔ", shi: "ㄕ", ri: "ㄖ", zi: "ㄗ", ci: "ㄘ", si: "ㄙ" };
  if (EMPTY_RHYME[base]) return EMPTY_RHYME[base] + TONE_MARK[tone];
  if (base === "m" || base === "n" || base === "ng") {
    // 嘸/嗯/哼 style: map to ㄇ/ㄣ nasal; tone kept
    const m = { m: "ㄇ", n: "ㄣ", ng: "ㄫ" };
    return m[base] + TONE_MARK[tone];
  }

  // Glide normalization (y/w)
  if (base.startsWith("yu")) base = "ü" + base.slice(2);
  else if (base.startsWith("yi")) base = "i" + base.slice(2);
  else if (base === "yong") base = "iong";
  else if (base.startsWith("y")) base = "i" + base.slice(1);
  else if (base.startsWith("wu")) base = "u" + base.slice(2);
  else if (base === "weng" || base === "wong") base = "ong";
  else if (base.startsWith("w")) base = "u" + base.slice(1);

  // Split initial + final
  let initial = "", rest = base;
  for (const key of ["zh", "ch", "sh"]) {
    if (rest.startsWith(key)) { initial = key; rest = rest.slice(2); break; }
  }
  if (!initial && rest.length > 1 && INITIALS[rest[0]]) { initial = rest[0]; rest = rest.slice(1); }

  // j/q/x/y-context: u-series is really ü-series
  if ((initial === "j" || initial === "q" || initial === "x") && rest.startsWith("u")) {
    rest = "ü" + rest.slice(1);
  }

  const initialSym = initial ? INITIALS[initial] : "";
  const finalSym = FINALS[rest];
  if (initial && !initialSym) return null;
  if (!finalSym) return null;
  return initialSym + finalSym + TONE_MARK[tone];
}

const text = await readFile(input, "utf8");
const entries = new Map();
const failures = [];
for (const line of text.split("\n")) {
  if (!line.startsWith("U+")) continue;
  const parts = line.split("\t");
  if (parts[1] !== "kMandarin") continue;
  const cp = parseInt(parts[0].slice(2), 16);
  const char = String.fromCodePoint(cp);
  const reading = pinyinToBopomofo(parts[2].trim());
  if (!reading) {
    // A single char with a two-syllable reading (e.g. túnwǎ: two tone marks)
    // has no single bopomofo form; skip it quietly instead of failing the build.
    const toneMarks = (parts[2].match(/[̄́̌̀āáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜńňǹ]/g) || []).length;
    if (toneMarks >= 2) continue;
    failures.push(`${parts[0]} ${parts[2].trim()}`); continue;
  }
  if (!entries.has(char)) entries.set(char, reading); // keep first occurrence
}

console.log(`parsed ${entries.size} chars, ${failures.length} failures`);
if (failures.length) {
  console.log("FAILURES:");
  console.log(failures.slice(0, 60).join("\n"));
  if (failures.length > 60) console.log(`... and ${failures.length - 60} more`);
  process.exit(1);
}

const syllables = [...new Set(entries.values())];
const width = syllables.length <= 36 * 36 ? 2 : 3;
const idxOf = new Map(syllables.map((s, i) => [s, i]));
const chars = [...entries.keys()].sort((a, b) => a.codePointAt(0) - b.codePointAt(0));
const charsStr = chars.join("");
let indexStr = "";
for (const ch of chars) indexStr += idxOf.get(entries.get(ch)).toString(36).padStart(width, "0");

const out = `// Auto-generated by scripts/build-bopomofo-data.mjs from Unihan kMandarin. Do not edit by hand.
export const BPMF_SYLLABLES: string[] = ${JSON.stringify(syllables)};
export const BPMF_CHARS = ${JSON.stringify(charsStr)};
export const BPMF_INDEX = ${JSON.stringify(indexStr)};
export const BPMF_INDEX_WIDTH = ${width};

const _chars = [...BPMF_CHARS];
const _map = new Map<string, string>();
for (let i = 0; i < _chars.length; i++) {
  _map.set(_chars[i], BPMF_SYLLABLES[parseInt(BPMF_INDEX.slice(i * BPMF_INDEX_WIDTH, (i + 1) * BPMF_INDEX_WIDTH), 36)]);
}

/** Look up a single CJK character's bopomofo reading (first/most-common reading). Returns undefined when unknown. */
export function bopomofoOf(char: string): string | undefined {
  return _map.get(char);
}
export const BPMF_COUNT = _chars.length;
`;
await writeFile(path.join(process.cwd(), "src/data/bopomofo.ts"), out);
console.log(`wrote src/data/bopomofo.ts (${chars.length} chars, ${syllables.length} unique syllables, index width ${width})`);
